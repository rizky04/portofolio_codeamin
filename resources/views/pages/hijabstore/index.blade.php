<script>
    const pages = ['beranda', 'katalog', 'pashmina', 'tentang'];
    const navMap = { beranda: 'nav-beranda', katalog: 'nav-katalog', pashmina: 'nav-katalog', tentang: 'nav-tentang' };

    function showPage(name) {
        pages.forEach(p => {
            document.getElementById('page-' + p).classList.remove('active');
        });
        document.getElementById('page-' + name).classList.add('active');

        // update nav active state
        ['nav-beranda', 'nav-katalog', 'nav-tentang'].forEach(id => {
            const el = document.getElementById(id);
            el.classList.remove('text-primary', 'font-bold', 'border-b-2', 'border-primary');
            el.classList.add('text-on-surface-variant');
        });
        const activeNav = navMap[name];
        if (activeNav) {
            const el = document.getElementById(activeNav);
            el.classList.remove('text-on-surface-variant');
            el.classList.add('text-primary', 'font-bold', 'border-b-2', 'border-primary');
        }

        window.scrollTo({ top: 0, behavior: 'smooth' });
    }

    // Glass nav scroll effect
    window.addEventListener('scroll', () => {
        const nav = document.getElementById('main-nav');
        if (window.scrollY > 20) {
            nav.classList.add('scrolled');
        } else {
            nav.classList.remove('scrolled');
        }
    });

    // set initial nav active
    showPage('beranda');
</script>
